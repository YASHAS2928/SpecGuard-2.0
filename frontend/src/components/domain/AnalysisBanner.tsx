import type { AnalysisMetadata } from '../../api/types'
import { ProvenanceBadge } from '../ui'

export function AnalysisBanner({ analysis }: { analysis: AnalysisMetadata }) {
  const fake = analysis.mode === 'fake'
  return (
    <div
      className={`rounded-md border px-3 py-2 text-sm ${
        fake ? 'border-warn/30 bg-warn/10' : 'border-prov-ai/30 bg-prov-ai/10'
      }`}
    >
      <div className="flex flex-wrap items-center gap-2">
        <ProvenanceBadge source="ai" label={fake ? 'AI · offline fake' : `AI · ${analysis.provider}`} />
        <span className="font-medium">
          {fake
            ? 'Generated by the offline fake provider. No language model was used.'
            : `Generated by ${analysis.provider}${analysis.model ? ` (${analysis.model})` : ''}.`}
        </span>
      </div>
      <p className="mt-1 text-xs text-fg-2">
        Prompt {analysis.prompt_version} · {analysis.retries} retr{analysis.retries === 1 ? 'y' : 'ies'} ·
        valid on first try: {analysis.valid_first_try ? 'yes' : 'no'}
        {analysis.latency_ms !== null ? ` · ${analysis.latency_ms} ms` : ''}
      </p>
      {analysis.message && <p className="mt-1 text-xs text-fg-2">{analysis.message}</p>}
    </div>
  )
}
