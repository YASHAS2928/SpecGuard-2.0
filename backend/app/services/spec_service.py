def _error_summary(exc: ValidationError) -> list[dict[str, str]]:
    return [
        {"loc": ".".join(str(part) for part in error["loc"]), "msg": error["msg"]}
        for error in exc.errors()[:10]
    ]


def _retries_from(exc: ApiError) -> int:
    if isinstance(exc.details, dict):
        value = exc.details.get("retries")
        if isinstance(value, int) and value >= 0:
            return value
    return 0


def _log_failed_call(
    db: Session,
    ai: RequirementAI,
    *,
    input_hash: str,
    error_code: str,
    retries: int,
    prompt_version: str = "n/a",
    latency_ms: int | None = None,
) -> None:
    """Persist a failed AI call immediately (it must survive the request error)."""
    db.add(
        LlmCall(
            stage=LlmStage.EXTRACTION,
            provider=AIProvider(ai.provider),
            model=ai.model,
            prompt_version=prompt_version,
            input_hash=input_hash,
            output_hash=None,
            valid_first_try=False,
            retries=retries,
            latency_ms=latency_ms,
            fallback=False,
            error_code=error_code,
        )
    )
    db.commit()


def analyze_requirement_version(
    db: Session,
    version_id: uuid.UUID,
    payload: AnalyzeRequirementRequest,
    *,
    ai: RequirementAI,
    checker: SpecChecker | None,
    trace_id: str | None,
) -> AnalyzeRequirementResponse:
    """Run AI extraction for a requirement version and store a DRAFT specification."""
    require_role(payload.actor_role, SPEC_EDITOR_ROLES, "analyse requirements")
    version = _get_version(db, version_id)
    requirement = version.requirement

    existing = list(db.scalars(select(Spec).where(Spec.requirement_version_id == version.id)))
    if any(spec.status == SpecStatus.APPROVED for spec in existing) and not payload.force:
        raise ConflictError(
            "An approved specification already exists for this requirement version. "
            "Set force=true to draft a new one.",
            details={"requirement_version_id": str(version.id)},
        )

    policies = _policies_for_version(db, version)
    input_hash = sha256_hex(
        {
            "requirement_text": version.text,
            "policies": [
                {"ref": policy.ref, "rule_text": policy.rule_text} for policy in policies
            ],
        }
    ) or ""

    try:
        result = ai.extract_requirement(requirement_text=version.text, policies=policies)
    except ApiError as exc:
        _log_failed_call(
            db, ai, input_hash=input_hash, error_code=exc.code.value, retries=_retries_from(exc)
        )
        raise
    except Exception as exc:
        _log_failed_call(
            db, ai, input_hash=input_hash, error_code=ErrorCode.AI_PROVIDER_ERROR.value, retries=0
        )
        raise AIProviderError(
            f"The AI provider failed unexpectedly ({type(exc).__name__})."
        ) from exc

    if not isinstance(result, AIResult):
        _log_failed_call(
            db, ai, input_hash=input_hash, error_code=ErrorCode.AI_OUTPUT_INVALID.value, retries=0
        )
        raise AIOutputInvalidError("The AI provider returned an invalid result envelope.")

    try:
        extraction = RequirementExtraction.model_validate(result.data.model_dump(mode="json"))
    except (ValidationError, AttributeError) as exc:
        _log_failed_call(
            db,
            ai,
            input_hash=input_hash,
            error_code=ErrorCode.AI_OUTPUT_INVALID.value,
            retries=result.retries,
            prompt_version=result.prompt_version,
            latency_ms=result.latency_ms,
        )
        raise AIOutputInvalidError(
            "The AI provider returned output that does not match the extraction contract.",
            details={"errors": _error_summary(exc) if isinstance(exc, ValidationError) else []},
        ) from exc

    llm_call = LlmCall(
        stage=LlmStage.EXTRACTION,
        provider=result.provider,
        model=result.model,
        prompt_version=result.prompt_version,
        input_hash=input_hash,
        output_hash=sha256_hex(extraction.model_dump(mode="json")),
        valid_first_try=result.valid_first_try,
        retries=result.retries,
        latency_ms=result.latency_ms,
        tokens_in=result.tokens_in,
        tokens_out=result.tokens_out,
        fallback=False,
    )
    db.add(llm_call)
    db.commit()

    parent = _latest_approved_spec_of_earlier_version(db, version)
    spec = Spec(
        requirement_version_id=version.id,
        version=max((item.version for item in existing), default=0) + 1,
        status=SpecStatus.DRAFT,
        inputs=[item.model_dump(mode="json") for item in extraction.inputs],
        outputs=list(extraction.outputs),
        assumptions=[item.model_dump(mode="json") for item in extraction.assumptions],
        parent_spec_id=parent.id if parent is not None else None,
        analysis_llm_call_id=llm_call.id,
    )
    for rule in extraction.rules:
        spec.rules.append(
            SpecRule(
                rule_key=rule.rule_key,
                type=RuleType(rule.type),
                params=rule.params.model_dump(mode="json"),
                origin=RuleOrigin(rule.origin),
                policy_ref=rule.policy_ref,
                source_span=rule.source_span,
                description=rule.description,
                grounded=None,
            )
        )
    for amb in extraction.ambiguities:
        spec.ambiguities.append(
            AmbiguityRecord(
                amb_code=amb.amb_code,
                question=amb.question,
                why=amb.why,
                affects_rules=list(amb.affects_rules),
                options=[option.model_dump(mode="json") for option in amb.options],
                status=AmbiguityStatus.OPEN,
            )
        )
    db.add(spec)
    db.flush()

    for old in existing:
        if old.status == SpecStatus.DRAFT:
            before_old = _spec_status_snapshot(old)
            assert_spec_transition(SpecStatus(old.status), SpecStatus.SUPERSEDED)
            old.status = SpecStatus.SUPERSEDED
            record_audit_event(
                db,
                actor=payload.actor,
                actor_role=payload.actor_role,
                action=AuditAction.SPEC_SUPERSEDED,
                entity_type=EntityType.SPEC,
                entity_id=old.id,
                before=before_old,
                after=_spec_status_snapshot(old),
                trace_id=trace_id,
                detail={"superseded_by": str(spec.id), "reason": "requirement re-analysed"},
            )

    checker_issues: list[ValidationIssue] = []
    if checker is not None:
        try:
            checker_issues = list(checker(extraction, version.text, policies))
            rule_keys = {rule.rule_key for rule in spec.rules}
            for issue in checker_issues:
                if not isinstance(issue, ValidationIssue):
                    raise TypeError("The checker must return ValidationIssue records.")
                if issue.code == ValidationCode.V02_UNGROUNDED_SPAN:
                    rule_key = (issue.detail or {}).get("rule_key")
                    if not isinstance(rule_key, str) or rule_key not in rule_keys:
                        raise ValueError("A grounding failure must identify a known rule.")
        except Exception as exc:
            raise IntegrationUnavailableError(
                f"The Quality Engine grounding check failed ({type(exc).__name__})."
            ) from exc
        ungrounded = {
            (issue.detail or {}).get("rule_key")
            for issue in checker_issues
            if issue.code == ValidationCode.V02_UNGROUNDED_SPAN
        }
        for rule_row in spec.rules:
            rule_row.grounded = rule_row.rule_key not in ungrounded
        _store_checker_issues(db, spec, checker_issues)
    refresh_unresolved_parameter_issues(db, spec)

    if version.version == requirement.latest_version and requirement.status == RequirementStatus.DRAFT:
        requirement.status = RequirementStatus.ANALYZED
        requirement.updated_at = utc_now()

    record_audit_event(
        db,
        actor=payload.actor,
        actor_role=payload.actor_role,
        action=AuditAction.REQUIREMENT_ANALYZED,
        entity_type=EntityType.SPEC,
        entity_id=spec.id,
        after=spec_snapshot(spec),
        trace_id=trace_id,
        detail={
            "requirement_version_id": str(version.id),
            "llm_call_id": str(llm_call.id),
            "provider": result.provider.value,
            "model": result.model,
            "prompt_version": result.prompt_version,
            "rule_count": len(spec.rules),
            "ambiguity_count": len(spec.ambiguities),
            "grounding_checked": checker is not None,
        },
    )
    db.commit()

    messages: list[str] = []
    if result.provider is AIProvider.FAKE:
        messages.append(FAKE_MESSAGE)
    if checker is None:
        messages.append(NO_CHECK_MESSAGE)
    return AnalyzeRequirementResponse(
        spec=build_spec_response(db, spec),
        analysis=AnalysisMetadata(
            mode=AnalysisMode.FAKE if result.provider is AIProvider.FAKE else AnalysisMode.LLM,
            provider=result.provider,
            model=result.model,
            prompt_version=result.prompt_version,
            valid_first_try=result.valid_first_try,
            retries=result.retries,
            fallback_used=False,
            latency_ms=result.latency_ms,
            llm_call_id=llm_call.id,
            message=" ".join(messages) or None,
        ),
    )


