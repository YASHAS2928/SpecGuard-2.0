def _get_version(db: Session, version_id: uuid.UUID) -> RequirementVersion:
    version = db.scalars(
        select(RequirementVersion)
        .where(RequirementVersion.id == version_id)
        .options(selectinload(RequirementVersion.requirement))
    ).first()
    if version is None:
        raise NotFoundError(
            f"Requirement version {version_id} was not found.",
            details={"requirement_version_id": str(version_id)},
        )
    return version


def _get_spec(db: Session, spec_id: uuid.UUID) -> Spec:
    spec = db.scalars(
        select(Spec)
        .where(Spec.id == spec_id)
        .options(
            selectinload(Spec.rules),
            selectinload(Spec.ambiguities),
            selectinload(Spec.requirement_version).selectinload(RequirementVersion.requirement),
        )
    ).first()
    if spec is None:
        raise NotFoundError(
            f"Specification {spec_id} was not found.", details={"spec_id": str(spec_id)}
        )
    return spec


def _get_ambiguity(db: Session, ambiguity_id: uuid.UUID) -> AmbiguityRecord:
    ambiguity = db.get(AmbiguityRecord, ambiguity_id)
    if ambiguity is None:
        raise NotFoundError(
            f"Ambiguity {ambiguity_id} was not found.",
            details={"ambiguity_id": str(ambiguity_id)},
        )
    return ambiguity


def _policies_for_version(db: Session, version: RequirementVersion) -> list[PolicyResponse]:
    """Return the attached policies in the order they were cited."""
    return [
        PolicyResponse.model_validate(policy)
        for policy in resolve_policy_refs(db, version.policy_ids)
    ]


def _latest_approved_spec_of_earlier_version(
    db: Session, version: RequirementVersion
) -> Spec | None:
    return db.scalars(
        select(Spec)
        .join(RequirementVersion, Spec.requirement_version_id == RequirementVersion.id)
        .where(
            RequirementVersion.requirement_id == version.requirement_id,
            RequirementVersion.version < version.version,
            Spec.approved_at.is_not(None),
        )
        .order_by(RequirementVersion.version.desc(), Spec.approved_at.desc())
    ).first()


