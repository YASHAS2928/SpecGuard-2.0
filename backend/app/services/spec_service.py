def _approval_blockers(db: Session, spec: Spec) -> dict[str, list[str]]:
    blocking_codes = sorted(
        {
            ValidationCode(record.code).value
            for record in _active_issue_records(db, spec.id)
            if record.severity == IssueSeverity.BLOCK
        }
    )
    return {
        "open_ambiguities": sorted(
            amb.amb_code for amb in spec.ambiguities if amb.status == AmbiguityStatus.OPEN
        ),
        "deferred_ambiguities": sorted(
            amb.amb_code for amb in spec.ambiguities if amb.status == AmbiguityStatus.DEFERRED
        ),
        "unresolved_params": _unresolved_params(spec),
        "blocking_issues": blocking_codes,
        "ungrounded_rules": sorted(rule.rule_key for rule in spec.rules if rule.grounded is not True),
    }


def approve_spec(
    db: Session,
    spec_id: uuid.UUID,
    payload: ApproveSpecRequest,
    *,
    trace_id: str | None,
) -> SpecResponse:
    """Approve a DRAFT specification once every gate passes."""
    require_role(payload.actor_role, SPEC_EDITOR_ROLES, "approve specifications")
    spec = _get_spec(db, spec_id)
    assert_spec_transition(SpecStatus(spec.status), SpecStatus.APPROVED)

    blockers = _approval_blockers(db, spec)
    if any(blockers.values()):
        raise SpecNotApprovableError(
            f"Specification {spec.id} cannot be approved yet.", details=blockers
        )

    version = spec.requirement_version
    requirement = version.requirement
    before = spec_snapshot(spec)

    others = db.scalars(
        select(Spec)
        .join(RequirementVersion, Spec.requirement_version_id == RequirementVersion.id)
        .where(
            RequirementVersion.requirement_id == requirement.id,
            Spec.status == SpecStatus.APPROVED,
            Spec.id != spec.id,
        )
    ).all()
    for other in others:
        before_other = _spec_status_snapshot(other)
        assert_spec_transition(SpecStatus(other.status), SpecStatus.SUPERSEDED)
        other.status = SpecStatus.SUPERSEDED
        record_audit_event(
            db,
            actor=payload.actor,
            actor_role=payload.actor_role,
            action=AuditAction.SPEC_SUPERSEDED,
            entity_type=EntityType.SPEC,
            entity_id=other.id,
            before=before_other,
            after=_spec_status_snapshot(other),
            trace_id=trace_id,
            detail={"superseded_by": str(spec.id), "reason": "newer specification approved"},
        )

    spec.status = SpecStatus.APPROVED
    spec.approved_by = payload.actor
    spec.approved_at = utc_now()
    spec.updated_at = utc_now()
    if version.version == requirement.latest_version:
        requirement.status = RequirementStatus.SPEC_APPROVED
        requirement.updated_at = utc_now()

    db.add(
        Review(
            entity_type=EntityType.SPEC,
            entity_id=spec.id,
            decision=ReviewDecision.APPROVE,
            reviewer=payload.actor,
            reviewer_role=payload.actor_role,
            reason=payload.comment,
        )
    )
    record_audit_event(
        db,
        actor=payload.actor,
        actor_role=payload.actor_role,
        action=AuditAction.SPEC_APPROVED,
        entity_type=EntityType.SPEC,
        entity_id=spec.id,
        before=before,
        after=spec_snapshot(spec),
        trace_id=trace_id,
        detail={
            "requirement_id": str(requirement.id),
            "requirement_version": version.version,
            "comment": payload.comment,
            "superseded_spec_ids": [str(other.id) for other in others],
        },
    )
    db.commit()
    return build_spec_response(db, spec)
