"""Specification workflow: analyze a requirement version, resolve ambiguities, approve.

Rules enforced here:

* The AI only drafts. Failed AI calls are logged and surfaced; they are never
  replaced by canned data.
* A spec cannot be approved while ambiguities are unresolved, parameters are
  null, blocking validation issues exist, or any rule is not grounded.
* Clarification patches are applied only after every changed rule re-validates
  against its typed parameter model; a bad patch changes nothing.
* Every state change writes an audit event in the same transaction.
"""

