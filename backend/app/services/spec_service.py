def spec_snapshot(spec: Spec) -> dict[str, Any]:
    """Return the audit snapshot of a specification."""
    return {
        "id": str(spec.id),
        "version": spec.version,
        "status": SpecStatus(spec.status).value,
        "rules": [
            {
                "rule_key": rule.rule_key,
                "params": dict(rule.params),
                "origin": RuleOrigin(rule.origin).value,
                "grounded": rule.grounded,
            }
            for rule in sorted(spec.rules, key=lambda item: item.rule_key)
        ],
        "ambiguities": [
            {
                "amb_code": amb.amb_code,
                "status": AmbiguityStatus(amb.status).value,
                "chosen_option_index": amb.chosen_option_index,
            }
            for amb in sorted(spec.ambiguities, key=lambda item: item.amb_code)
        ],
    }


def _spec_status_snapshot(spec: Spec) -> dict[str, Any]:
    return {"id": str(spec.id), "version": spec.version, "status": SpecStatus(spec.status).value}


def _ambiguity_snapshot(spec: Spec, ambiguity: AmbiguityRecord) -> dict[str, Any]:
    affected = set(ambiguity.affects_rules)
    return {
        "amb_code": ambiguity.amb_code,
        "status": AmbiguityStatus(ambiguity.status).value,
        "chosen_option_index": ambiguity.chosen_option_index,
        "rules": [
            {
                "rule_key": rule.rule_key,
                "params": dict(rule.params),
                "origin": RuleOrigin(rule.origin).value,
            }
            for rule in sorted(spec.rules, key=lambda item: item.rule_key)
            if rule.rule_key in affected
        ],
    }


def _unresolved_params(spec: Spec) -> list[str]:
    return sorted(
        f"{rule.rule_key}.{name}"
        for rule in spec.rules
        for name, value in rule.params.items()
        if value is None
    )


def _active_issue_records(db: Session, spec_id: uuid.UUID) -> list[ValidationIssueRecord]:
    return list(
        db.scalars(
            select(ValidationIssueRecord)
            .where(ValidationIssueRecord.spec_id == spec_id, ValidationIssueRecord.active.is_(True))
            .order_by(ValidationIssueRecord.created_at, ValidationIssueRecord.field_path)
        )
    )


def _store_checker_issues(db: Session, spec: Spec, issues: Sequence[ValidationIssue]) -> None:
    rules_by_key = {rule.rule_key: rule for rule in spec.rules}
    for issue in issues:
        rule_key = (issue.detail or {}).get("rule_key")
        rule = rules_by_key.get(rule_key) if isinstance(rule_key, str) else None
        db.add(
            ValidationIssueRecord(
                spec_id=spec.id,
                entity_type=EntityType.RULE if rule else EntityType.SPEC,
                entity_id=rule.id if rule else spec.id,
                code=issue.code,
                severity=issue.severity,
                message=issue.message,
                field_path=issue.field_path,
                detail=to_json_safe(issue.detail),
                active=True,
            )
        )
    db.flush()


def refresh_unresolved_parameter_issues(db: Session, spec: Spec) -> None:
    """Replace the active V13 issues with the spec's current unresolved parameters."""
    for record in db.scalars(
        select(ValidationIssueRecord).where(
            ValidationIssueRecord.spec_id == spec.id,
            ValidationIssueRecord.code == ValidationCode.V13_UNRESOLVED_PARAMETER,
            ValidationIssueRecord.active.is_(True),
        )
    ):
        record.active = False

    pending = [amb for amb in spec.ambiguities if amb.status != AmbiguityStatus.RESOLVED]
    for rule in sorted(spec.rules, key=lambda item: item.rule_key):
        for name, value in sorted(rule.params.items()):
            if value is not None:
                continue
            path = f"/rules/{rule.rule_key}/params/{name}"
            addressed_by = sorted(
                {
                    amb.amb_code
                    for amb in pending
                    for option in amb.options
                    for op in option.get("patch", [])
                    if op.get("path") == path
                }
            )
            suffix = (
                ""
                if addressed_by
                else " No clarification option addresses it; edit the requirement and analyse again."
            )
            db.add(
                ValidationIssueRecord(
                    spec_id=spec.id,
                    entity_type=EntityType.RULE,
                    entity_id=rule.id,
                    code=ValidationCode.V13_UNRESOLVED_PARAMETER,
                    severity=IssueSeverity.BLOCK,
                    message=f"{rule.rule_key}.{name} is unresolved.{suffix}",
                    field_path=f"rules.{rule.rule_key}.params.{name}",
                    detail={"rule_key": rule.rule_key, "param": name, "addressed_by": addressed_by},
                    active=True,
                )
            )
    db.flush()


def build_spec_response(db: Session, spec: Spec) -> SpecResponse:
    """Build the API representation of a specification, including active issues."""
    records = _active_issue_records(db, spec.id)
    issues = [
        ValidationIssue(
            code=record.code,
            severity=record.severity,
            entity_type=record.entity_type,
            entity_id=record.entity_id,
            message=record.message,
            field_path=record.field_path,
            detail=dict(record.detail) if record.detail else None,
        )
        for record in records
    ]
    rules = [
        SpecRuleResponse(
            id=rule.id,
            rule_key=rule.rule_key,
            type=RuleType(rule.type),
            params=dict(rule.params),
            origin=RuleOrigin(rule.origin),
            policy_ref=rule.policy_ref,
            source_span=rule.source_span,
            description=rule.description,
            grounded=rule.grounded,
            unresolved_params=sorted(name for name, value in rule.params.items() if value is None),
        )
        for rule in sorted(spec.rules, key=lambda item: item.rule_key)
    ]
    ambiguities = [
        AmbiguityResponse(
            id=amb.id,
            spec_id=amb.spec_id,
            amb_code=amb.amb_code,
            question=amb.question,
            why=amb.why,
            affects_rules=list(amb.affects_rules),
            options=[ClarificationOption.model_validate(option) for option in amb.options],
            status=AmbiguityStatus(amb.status),
            chosen_option_index=amb.chosen_option_index,
            resolved_by=amb.resolved_by,
            resolved_at=amb.resolved_at,
        )
        for amb in sorted(spec.ambiguities, key=lambda item: item.amb_code)
    ]
    return SpecResponse.model_validate(
        {
            "id": spec.id,
            "requirement_version_id": spec.requirement_version_id,
            "version": spec.version,
            "status": SpecStatus(spec.status),
            "inputs": list(spec.inputs),
            "outputs": list(spec.outputs),
            "rules": rules,
            "ambiguities": ambiguities,
            "assumptions": list(spec.assumptions),
            "issues": issues,
            "open_ambiguities": sum(
                1 for amb in spec.ambiguities if amb.status != AmbiguityStatus.RESOLVED
            ),
            "blocking_issue_count": sum(
                1 for record in records if record.severity == IssueSeverity.BLOCK
            ),
            "parent_spec_id": spec.parent_spec_id,
            "approved_by": spec.approved_by,
            "approved_at": spec.approved_at,
            "created_at": spec.created_at,
        }
    )


def get_spec(db: Session, spec_id: uuid.UUID) -> SpecResponse:
    """Return one specification, or raise 404."""
    return build_spec_response(db, _get_spec(db, spec_id))


def list_specs_for_version(db: Session, version_id: uuid.UUID) -> list[SpecResponse]:
    """Return all specifications of a requirement version, oldest first."""
    version = _get_version(db, version_id)
    specs = db.scalars(
        select(Spec)
        .where(Spec.requirement_version_id == version.id)
        .options(selectinload(Spec.rules), selectinload(Spec.ambiguities))
        .order_by(Spec.version)
    ).all()
    return [build_spec_response(db, spec) for spec in specs]


