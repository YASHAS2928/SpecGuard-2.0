def _patch_error(message: str, details: dict[str, Any]) -> ApiError:
    return ApiError(
        message,
        details=details,
        code=ErrorCode.VALIDATION_ERROR,
        status_code=422,
    )


def _apply_patch(spec: Spec, ambiguity: AmbiguityRecord, option: ClarificationOption) -> None:
    """Validate every patch operation first, then apply them all (or none)."""
    rules = {rule.rule_key: rule for rule in spec.rules}
    new_params: dict[str, dict[str, Any]] = {}
    new_origins: dict[str, RuleOrigin] = {}

    for op in option.patch:
        rule = rules.get(op.rule_key)
        if rule is None:
            raise _patch_error(
                "The selected option targets a rule that is not in this specification.",
                {"amb_code": ambiguity.amb_code, "path": op.path},
            )
        parts = op.path.split("/")  # ["", "rules", KEY, "params", name] or [..., "origin"]
        if parts[3] == "origin":
            try:
                new_origins[rule.rule_key] = RuleOrigin(op.value)
            except ValueError as exc:
                raise _patch_error(
                    "The selected option sets an invalid rule origin.",
                    {"amb_code": ambiguity.amb_code, "path": op.path},
                ) from exc
        else:
            params = new_params.setdefault(rule.rule_key, dict(rule.params))
            params[parts[4]] = op.value

    validated: dict[str, dict[str, Any]] = {}
    for rule_key, params in new_params.items():
        model = PARAM_MODELS[RuleType(rules[rule_key].type)]
        try:
            validated[rule_key] = model.model_validate(params).model_dump(mode="json")
        except ValidationError as exc:
            raise _patch_error(
                "The selected option produces invalid rule parameters.",
                {
                    "amb_code": ambiguity.amb_code,
                    "rule_key": rule_key,
                    "errors": _error_summary(exc),
                },
            ) from exc

    for rule_key, params in validated.items():
        rules[rule_key].params = params
    for rule_key, origin in new_origins.items():
        rules[rule_key].origin = origin


def _promote_clarified_rules(spec: Spec, ambiguity: AmbiguityRecord) -> None:
    """Mark rules CLARIFIED once nothing about them is unresolved any more."""
    rules = {rule.rule_key: rule for rule in spec.rules}
    pending = [amb for amb in spec.ambiguities if amb.status != AmbiguityStatus.RESOLVED]
    for rule_key in ambiguity.affects_rules:
        rule = rules.get(rule_key)
        if (
            rule is not None
            and rule.origin == RuleOrigin.NEEDS_CLARIFICATION
            and all(value is not None for value in rule.params.values())
            and not any(rule_key in other.affects_rules for other in pending)
        ):
            rule.origin = RuleOrigin.CLARIFIED


def resolve_ambiguity(
    db: Session,
    ambiguity_id: uuid.UUID,
    payload: ResolveAmbiguityRequest,
    *,
    trace_id: str | None,
) -> SpecResponse:
    """Apply the chosen option's patch to the DRAFT spec, or defer the ambiguity."""
    require_role(payload.actor_role, SPEC_EDITOR_ROLES, "resolve ambiguities")
    ambiguity = _get_ambiguity(db, ambiguity_id)
    spec = _get_spec(db, ambiguity.spec_id)
    if spec.status != SpecStatus.DRAFT:
        raise StateTransitionError(
            "Ambiguities can only be resolved while the specification is DRAFT.",
            details={"spec_id": str(spec.id), "spec_status": SpecStatus(spec.status).value},
        )

    target = AmbiguityStatus.DEFERRED if payload.defer else AmbiguityStatus.RESOLVED
    assert_ambiguity_transition(AmbiguityStatus(ambiguity.status), target)
    before = _ambiguity_snapshot(spec, ambiguity)

    option_label: str | None = None
    if payload.defer:
        action = AuditAction.AMBIGUITY_DEFERRED
    else:
        index = payload.option_index
        if index is None or index >= len(ambiguity.options):
            raise _patch_error(
                "option_index is out of range for this ambiguity.",
                {"amb_code": ambiguity.amb_code, "option_count": len(ambiguity.options)},
            )
        option = ClarificationOption.model_validate(ambiguity.options[index])
        _apply_patch(spec, ambiguity, option)
        ambiguity.chosen_option_index = index
        ambiguity.resolved_by = payload.actor
        ambiguity.resolved_at = utc_now()
        option_label = option.label
        action = AuditAction.AMBIGUITY_RESOLVED

    ambiguity.status = target
    ambiguity.comment = payload.comment
    if not payload.defer:
        _promote_clarified_rules(spec, ambiguity)
    refresh_unresolved_parameter_issues(db, spec)
    spec.updated_at = utc_now()

    record_audit_event(
        db,
        actor=payload.actor,
        actor_role=payload.actor_role,
        action=action,
        entity_type=EntityType.AMBIGUITY,
        entity_id=ambiguity.id,
        before=before,
        after=_ambiguity_snapshot(spec, ambiguity),
        trace_id=trace_id,
        detail={
            "spec_id": str(spec.id),
            "amb_code": ambiguity.amb_code,
            "option_index": ambiguity.chosen_option_index,
            "option_label": option_label,
            "comment": payload.comment,
        },
    )
    db.commit()
    return build_spec_response(db, spec)


